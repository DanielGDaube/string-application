package com.pluralsight;

public class VariableApp {
    public static void main(String[] args) {
        String color;
        color = "purple";
        int year;
        year = 2026;
        char initial;
        initial = 'G';
        boolean pets;
        pets = true;
        String message;
        message = "Nice to meet you";

        System.out.println("My favorite color is " + color);
        System.out.println("I started this clas in the year " + year);
        System.out.println("My middle initial is " + initial);
        System.out.println("I have pets: " + pets);
        System.out.println("Nice message: " + message);


        int days = 7;
        double price = 4.99;
        char letter = 'F';
        boolean raining = false;

        System.out.println("There are " + days + " days in a week");
        System.out.println("The price of coffee is $" + price);
        System.out.println(letter + " is my favorite letter");
        System.out.println("Is it raining: " + raining);

    }
}
